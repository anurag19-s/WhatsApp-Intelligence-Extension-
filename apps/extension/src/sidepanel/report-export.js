'use strict';

(function (root) {
  function asArray(value) {
    return Array.isArray(value) ? value : [];
  }

  function textOf(item, key) {
    if (typeof item === 'string') return item;
    return item && typeof item[key || 'text'] === 'string' ? item[key || 'text'] : '';
  }

  function sourceLabel(item) {
    if (!item || !Array.isArray(item.sourceIndices) || item.sourceIndices.length === 0) return '';
    return ' (Sources: ' + item.sourceIndices.map((index) => '#' + index).join(', ') + ')';
  }

  function confidenceLabel(item) {
    return item && item.confidence ? ' [' + item.confidence + ' confidence]' : '';
  }

  function listMarkdown(items, key) {
    if (!items.length) return '- None identified in the selected messages.\n';
    return items.map((item) => '- ' + textOf(item, key) + sourceLabel(item) + confidenceLabel(item)).join('\n') + '\n';
  }

  function buildMarkdown(report, title) {
    const meta = report.meta || {};
    const decisions = report.decisions || {};
    let markdown = '# Corporate Intelligence Report: ' + (title || meta.conversationTitle || 'WhatsApp Conversation') + '\n\n';
    markdown += '**Provider:** ' + (meta.provider || (meta.isMock ? 'mock' : 'unknown')) +
      '  \n**Model:** ' + (meta.model || 'Not specified') +
      '  \n**Generated:** ' + (meta.generatedAt || meta.analyzedAt || 'Not specified') +
      '  \n**Selected messages:** ' + (meta.selectedCount || 0) + '\n\n';
    if (meta.isMock) markdown += '> MOCK OUTPUT — ' + (meta.warning || 'No AI interpretation was performed.') + '\n\n';

    markdown += '## Executive Summary\n' + (report.executiveSummary || 'No summary provided.') + '\n\n';
    markdown += '## Key Discussion Points\n' + listMarkdown(asArray(report.keyDiscussionPoints));
    markdown += '\n## Decisions and Agreements\n### Confirmed\n' +
      listMarkdown(asArray(decisions.confirmed || report.confirmedDecisions));
    markdown += '\n### Proposed\n' + listMarkdown(asArray(decisions.proposed || report.proposedDecisions));
    markdown += '\n### Ambiguous or unconfirmed\n' + listMarkdown(asArray(decisions.ambiguous));

    markdown += '\n## Action Items\n';
    const actions = asArray(report.actionItems);
    markdown += actions.length
      ? actions.map((item) => '- **Task:** ' + (item.task || '') +
        ' | **Owner:** ' + (item.owner || 'Unassigned') +
        ' | **Deadline:** ' + (item.deadline || 'Not specified') +
        ' | **Status:** ' + (item.status || 'pending') +
        sourceLabel(item) + confidenceLabel(item)).join('\n') + '\n'
      : '- None identified in the selected messages.\n';

    markdown += '\n## Approvals\n';
    const approvals = asArray(report.approvals);
    markdown += approvals.length
      ? approvals.map((item) => '- ' + (item.item || textOf(item)) +
        (item.owner ? ' (Owner: ' + item.owner + ')' : '') +
        sourceLabel(item) + confidenceLabel(item)).join('\n') + '\n'
      : listMarkdown(asArray(report.pendingApprovals));
    markdown += '\n## Unresolved Issues\n' + listMarkdown(asArray(report.unresolvedIssues));

    markdown += '\n## Risks and Watchpoints\n';
    const risks = asArray(report.risks);
    markdown += risks.length
      ? risks.map((item) => '- **' + (item.type || 'risk') + ':** ' +
        textOf(item, 'description') + sourceLabel(item) + confidenceLabel(item)).join('\n') + '\n'
      : listMarkdown(asArray(report.importantRisks));
    if (!risks.length && !asArray(report.importantRisks).length) {
      markdown += '\nNo risks were identified in this report; this does not establish that no risk exists.\n';
    }

    markdown += '\n## Recommended Next Steps\n' + listMarkdown(asArray(report.recommendedNextSteps));
    markdown += '\n---\nGenerated by WA Corporate Intelligence. Verify AI interpretations against the cited source messages.\n';
    return markdown;
  }

  function csvCell(value) {
    let text = value === null || value === undefined ? '' : String(value);
    if (/^[\t\r ]*[=+\-@]/.test(text)) text = "'" + text;
    return '"' + text.replace(/"/g, '""') + '"';
  }

  function buildCsv(report) {
    const rows = [[
      'Task',
      'Owner',
      'Deadline',
      'Status',
      'Confidence',
      'Source references',
    ]];
    asArray(report.actionItems).forEach((item) => {
      rows.push([
        item.task || '',
        item.owner || 'Unassigned',
        item.deadline || 'Not specified',
        item.status || 'pending',
        item.confidence || '',
        asArray(item.sourceIndices).map((index) => '#' + index).join('; '),
      ]);
    });
    return rows.map((row) => row.map(csvCell).join(',')).join('\r\n') + '\r\n';
  }

  const api = { buildMarkdown, buildCsv };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  if (root) root.WACIReportExport = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
